namespace ChessInfrastructure.Models.Analysis;

/// <summary>
/// Ответ движка об анализируемой позиции: оценка, основная линия и статистика поиска
/// </summary>
/// <remarks>
/// Nullable-поля могут отсутствовать в ответе движка, null не означает нулевое значение
/// Оценки сохраняются со стороны очереди хода исходной позиции, без приведения к белым
/// </remarks>
public sealed record EngineMoveInfo
{
    /// <summary>
    /// Выбранный движком ход из ответа bestmove в UCI-нотации, например e2e4 или e7e8q
    /// При ослабленной игре может отличаться от первого хода основной линии Pv
    /// Отсутствует, если допустимых ходов нет или ответ bestmove еще не обработан
    /// </summary>
    public string? BestMove { get; init; }

    /// <summary>
    /// Основная достигнутая глубина поиска в полуходах: один ход одной стороны равен одному полуходу
    /// Выборочные продления и сокращения поиска означают, что отдельные ветки исследованы на разную глубину
    /// </summary>
    public int? Depth { get; init; }

    /// <summary>
    /// Максимальная достигнутая глубина отдельных веток поиска в полуходах, поле UCI seldepth
    /// Показывает, насколько далеко движок заглянул в отдельных продолжениях, а не глубину всех вариантов
    /// </summary>
    public int? SelectiveDepth { get; init; }

    /// <summary>
    /// Номер варианта при расчете нескольких продолжений, начиная с единицы, поле UCI multipv
    /// Значение 1 соответствует основной линии, последующие номера обозначают альтернативы
    /// </summary>
    public int? MultiPv { get; init; }

    /// <summary>
    /// Оценка позиции в сотых долях пешки со стороны очереди хода исходной позиции
    /// Например, +100 отображается как +1.00 в пользу ходящей стороны и не обязательно означает лишнюю пешку
    /// Матовая оценка хранится отдельно в MateIn
    /// </summary>
    public int? ScoreCp { get; init; }

    /// <summary>
    /// Матовая оценка в ходах, а не полуходах, со стороны очереди хода исходной позиции
    /// Положительное значение означает найденный мат сопернику, отрицательное означает мат ходящей стороне
    /// Ноль обозначает уже поставленный мат, null означает отсутствие матовой оценки
    /// </summary>
    public int? MateIn { get; init; }

    /// <summary>
    /// Маркер границы оценки: lowerbound означает не ниже указанного значения, upperbound означает не выше
    /// Null означает, что маркер границы отсутствует
    /// Граничные оценки нельзя использовать как точные значения для вычисления потери оценки
    /// </summary>
    public string? ScoreBound { get; init; }

    /// <summary>
    /// Количество просмотренных узлов в текущем поиске, включая повторные посещения позиций
    /// Используется для диагностики объема выполненного расчета
    /// </summary>
    public long? Nodes { get; init; }

    /// <summary>
    /// Скорость поиска в узлах в секунду, поле UCI nps
    /// Зависит от оборудования и позиции и сама по себе не определяет качество найденного хода
    /// </summary>
    public long? NodesPerSecond { get; init; }

    /// <summary>
    /// Приблизительная заполненность хеш-таблицы актуальными записями поиска в промилле, поле UCI hashfull
    /// Например, 500 означает около 50 процентов, 1000 означает около 100 процентов
    /// Это не объем занятой оперативной памяти
    /// </summary>
    public int? HashFull { get; init; }

    /// <summary>
    /// Количество успешных обращений к эндшпильным таблицам в ходе поиска, поле UCI tbhits
    /// Такие таблицы содержат заранее рассчитанные результаты позиций с небольшим числом фигур
    /// </summary>
    public long? TablebaseHits { get; init; }

    /// <summary>
    /// Время с начала текущего поиска в миллисекундах, поле UCI time
    /// Не включает ожидание задания в очереди или блокировки сервиса
    /// </summary>
    public long? TimeMs { get; init; }

    /// <summary>
    /// Основная линия продолжения в UCI-нотации, поле UCI pv, с чередованием ходов обеих сторон
    /// Начинается из анализируемой позиции, например e2e4, e7e5, g1f3
    /// Длина линии не обязана совпадать с Depth, пустой массив означает отсутствие продолжения
    /// </summary>
    public string[] Pv { get; init; } = [];
}
